"""Writes the two samples of polarized imaging (exercise 7): magnet_solenoid.yml and nwa7034_fragment.yml.

    python gen_polarized.py

Their magnetic fields are maps on a grid (odin_polarized.py); the volumes written here give their attenuation in the
ordinary images (camera, Timepix) and their drawing.

  * magnet_solenoid: the solenoid of M. Sales et al., Three Dimensional Polarimetric Neutron Tomography of Magnetic
    Fields, Sci. Rep. 8, 2214 (2018), measured at RADEN (J-PARC): 13.5 windings of aluminium wire 1 mm thick, length
    15.5 mm, radius 5.5 mm, 0.6 A, its axis along x tilted by about 9° (as in the paper). The wire is drawn by spheres
    of 1 mm along the helix (and its two leads, going up). Its field: odin_polarized.solenoid_field (Biot–Savart).
  * nwa7034_fragment: the fragment of NWA 7034 of C. Qvistgaard et al., Geochem. Geophys. Geosyst. 27, e2025GC012641
    (2026): 2 mm thick, about 10 mm wide and 13 mm tall, magnetized with a small whiteboard magnet before the
    measurement (no remanent field was left in it); measured at RADEN at 33 angles. Its field and its attenuation: the
    authors' reconstruction (data DTU Data, doi:10.11583/DTU.30775208, CC BY 4.0). Drawn as a plate of the matrix of
    the meteorite (same material as meteorite_nwa7034.yml).
"""
import os

import numpy as np
import yaml

HERE = os.path.dirname(os.path.abspath(__file__))


def solenoid():
    length, radius, turns, tilt = 15.5, 5.5, 13.5, np.radians(9.0)
    n = int(2 * np.pi * radius * turns / 1.0)                  # a sphere every millimeter of wire
    s = np.linspace(0, 1, n)
    th = 2 * np.pi * turns * s
    pts = np.c_[length * (s - 0.5), radius * np.cos(th), radius * np.sin(th)]
    up = np.arange(1.0, 9.0, 1.0)                               # the leads, up to the edge of the field of view
    pts = np.r_[np.c_[np.full(up.size, pts[0, 0]), pts[0, 1] + up, np.full(up.size, pts[0, 2])], pts,
                np.c_[np.full(up.size, pts[-1, 0]), pts[-1, 1] + up, np.full(up.size, pts[-1, 2])]]
    R = np.array([[np.cos(tilt), 0, np.sin(tilt)], [0, 1, 0], [-np.sin(tilt), 0, np.cos(tilt)]])
    pts = pts @ R.T
    vols = [dict(material="aluminium wire", shape="sphere", center_mm=[round(float(c), 3) for c in p],
                 size_mm=[1.0, 1.0, 1.0]) for p in pts]
    return {
        "name": "Solenoid (Sales et al. 2018), 0.6 A",
        "description": (
            "A small coil of aluminium wire (1 mm thick): 13.5 windings, 15.5 mm long, 11 mm in diameter, its axis "
            "horizontal (x, across the beam, tilted by about 9°), a current of 0.6 A. The current makes a magnetic field "
            "of about half a millitesla inside it, along its axis, which turns the spin of the neutrons that cross it. "
            "The sample of a polarized-imaging tomography at RADEN (J-PARC), Sales et al. (2018)."),
        "formula": "Al (wire); field of 0.5 mT inside",
        "hybrid_only": True,
        "field": "solenoid",
        "reference": ("M. Sales et al., Three Dimensional Polarimetric Neutron Tomography of "
                      "Magnetic Fields, Sci. Rep. 8, 2214 (2018). Generated by odin/samples/gen_polarized.py."),
        "materials": {"aluminium wire": "Al_sg225.ncmat"},
        "volumes": vols,
    }


def fragment():
    return {
        "name": "Magnetized fragment of NWA 7034 (Qvistgaard et al. 2026)",
        "description": (
            "A fragment of the Martian meteorite NWA 7034, 2 mm thick, about 10 mm wide and 13 mm tall, standing on "
            "the rotation stage (its thickness along the beam at 0°). It held no field of its own: it was magnetized "
            "with a small whiteboard magnet before the measurement; its magnetic minerals (iron oxides) keep a field "
            "of a few millitesla. Measured by polarized imaging at RADEN (J-PARC) at 33 angles, Qvistgaard et al. "
            "(2026)."),
        "formula": "matrix of NWA 7034 (plagioclase, pyroxenes, Fe oxides); magnetized Fe oxides",
        "hybrid_only": True,
        "field": "nwa7034",
        "reference": ("C. H. Qvistgaard, E. B. Naver et al., Geochem. Geophys. Geosyst. 27, e2025GC012641 (2026); field "
                      "and data: DTU Data, doi:10.11583/DTU.30775208 (CC BY 4.0). Generated by "
                      "odin/samples/gen_polarized.py."),
        "materials": {"matrix": "phases<0.9754*solid::Na106Ca244Al275Si1088O3831Mg299Fe480P30Cl10/3.290gcm3&"
                                "0.0246*stdlib::LiquidWaterH2O_T293.6K.ncmat>"},
        "volumes": [dict(material="matrix", center_mm=[0, 0, 0], size_mm=[10.0, 13.0, 2.0])],
    }


def main():
    for name, spec in (("magnet_solenoid", solenoid()), ("nwa7034_fragment", fragment())):
        with open(os.path.join(HERE, name + ".yml"), "w", encoding="utf-8") as f:
            f.write("# Generated by gen_polarized.py (do not edit by hand).\n")
            yaml.safe_dump(spec, f, sort_keys=False, allow_unicode=True, width=120)
        print(name, len(spec["volumes"]), "volumes")


if __name__ == "__main__":
    main()
