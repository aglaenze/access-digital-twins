"""Writes steel_tensile.yml: the tensile specimen of austenitic stainless steel measured at V20 (the ESS test beamline at
HZB, Berlin), without load and under 600 MPa, by Bragg-edge imaging with wavelength frame multiplication.

    python gen_steel_v20.py

Source: the measurement of September 2018 (P. Kadletz), public data of the ESS repository scipp/ess-notebooks-data
(imaging/bragg-edge-imaging-2D), analyzed against the twin of V20 in notebook 14 of the ODIN training series; the
beamline: R. Woracek et al., Nucl. Instrum. Methods A 839, 102 (2016). What is taken from the data (notebook 14):
  * a flat specimen pulled along x (horizontal in the image), 9.8 mm wide (y), narrowed in its middle to 6.4 mm by two
    circular arcs; 2.8 mm thick (the thickness fitted on its transmission, about 72 % over all wavelengths);
  * austenitic stainless steel (fcc), a = 3.606 Å (its (111), (200), (220) edges), a type 304 composition;
  * 600 MPa nominal in the narrowest section; E ≈ 195 GPa and ν ≈ 0.29 (typical values for this steel);
  * the measured strain across the specimen (along the beam): −7.6 ± 3.0 × 10⁻⁴ (expected −8.6 × 10⁻⁴ at the center).
What is assumed: the length of the narrowing (8 mm, arcs of radius 5.6 mm), the length of the specimen in the field of
view, and a uniform stress F/A in each thin slice of the specimen (no stress concentration, no texture: the real
specimen has a <110> fiber texture).
"""
import os

import numpy as np
import yaml

HERE = os.path.dirname(os.path.abspath(__file__))
WIDE, NARROW, THICK = 9.8, 6.4, 2.8          # mm
HALF_NARROWING = 4.0                          # mm: the arcs span |x| < 4 mm
D = (WIDE - NARROW) / 2                       # depth of each arc
R = (HALF_NARROWING ** 2 + D ** 2) / (2 * D)  # radius of the arcs
SLICE = 0.2                                   # mm: width of the slices that draw the arcs
MATERIAL = "SS304_V20.ncmat;atomdb=Fe:is:0.70:Fe:0.19:Cr:0.11:Ni"


def height(x):
    """Width of the specimen (along y) at position x [mm]."""
    return float(np.where(np.abs(x) < HALF_NARROWING, NARROW + 2 * (R - np.sqrt(R ** 2 - x ** 2)), WIDE))


def main():
    vols = []
    xs = np.arange(-HALF_NARROWING + SLICE / 2, HALF_NARROWING, SLICE)
    for x in xs:
        vols.append(dict(material="steel", center_mm=[round(float(x), 4), 0, 0],
                         size_mm=[SLICE, round(height(x), 4), THICK]))
    for sign in (-1, 1):                       # the wide ends, out to the edges of the field of view
        vols.append(dict(material="steel", center_mm=[sign * (HALF_NARROWING + 4.0), 0, 0], size_mm=[8.0, WIDE, THICK]))
    F600 = 600 * NARROW * THICK / 1000         # kN giving 600 MPa in the narrowest section
    spec = {
        "name": "Steel tensile specimen (V20, austenitic stainless steel)",
        "description": (
            "A flat tensile specimen of austenitic stainless steel (type 304, face-centered cubic), 2.8 mm thick, held "
            "in a load frame that pulls it along x (horizontal in the image). It is 9.8 mm wide, narrowed in its middle "
            "to 6.4 mm by two circular arcs: the same force crosses every section, so the stress is largest in the "
            f"middle. The specimen measured at V20 (HZB) in 2018, at 0 and 600 MPa ({F600:.2f} kN)."),
        "formula": "Fe0.70Cr0.19Ni0.11 (fcc)",
        "hybrid_only": True,
        "reference": ("V20 measurement of September 2018 (P. Kadletz), data scipp/ess-notebooks-data; V20: R. Woracek "
                      "et al., Nucl. Instrum. Methods A 839, 102 (2016). Generated by odin/samples/gen_steel_v20.py."),
        "load": {"axis": "x", "max_kN": round(F600 * 1.02, 2), "young_GPa": 195, "poisson": 0.29},
        "materials": {"steel": MATERIAL},
        "volumes": vols,
    }
    with open(os.path.join(HERE, "steel_tensile.yml"), "w", encoding="utf-8") as f:
        f.write("# Generated by gen_steel_v20.py (do not edit by hand): the V20 tensile specimen.\n")
        yaml.safe_dump(spec, f, sort_keys=False, allow_unicode=True, width=120)
    print(f"{len(vols)} volumes; 600 MPa at {F600:.3f} kN; arcs of radius {R:.2f} mm")


if __name__ == "__main__":
    main()
